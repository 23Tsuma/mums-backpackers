CREATE TABLE IF NOT EXISTS booking_requests (
  id CHAR(36) NOT NULL,
  reference VARCHAR(40) NOT NULL,
  idempotency_key CHAR(36) NOT NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(40) NOT NULL DEFAULT '',
  checkin DATE NOT NULL,
  checkout DATE NOT NULL,
  guests VARCHAR(16) NOT NULL,
  accommodation_type VARCHAR(120) NOT NULL DEFAULT '',
  special_requests VARCHAR(2000) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL DEFAULT 'Pending Confirmation',
  submitter_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  customer_email_sent_at DATETIME(3) NULL,
  admin_email_sent_at DATETIME(3) NULL,
  customer_email_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  admin_email_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  customer_email_claimed_at DATETIME(3) NULL,
  admin_email_claimed_at DATETIME(3) NULL,
  customer_email_next_attempt_at DATETIME(3) NULL,
  admin_email_next_attempt_at DATETIME(3) NULL,
  customer_email_last_error VARCHAR(1000) NULL,
  admin_email_last_error VARCHAR(1000) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_booking_reference (reference),
  UNIQUE KEY uq_booking_idempotency (idempotency_key),
  KEY idx_booking_rate_limit (submitter_hash, created_at),
  KEY idx_booking_admin_retry (admin_email_sent_at, admin_email_next_attempt_at, admin_email_attempts, created_at),
  KEY idx_booking_customer_retry (customer_email_sent_at, customer_email_next_attempt_at, customer_email_attempts, created_at),
  CONSTRAINT chk_booking_checkout_after_checkin CHECK (checkout > checkin),
  CONSTRAINT chk_booking_guests CHECK (guests IN ('1 guest', '2 guests', '3 guests', '4+ guests')),
  CONSTRAINT chk_booking_status CHECK (
    status IN ('Pending Confirmation', 'Confirmed', 'Declined', 'Cancelled', 'Completed')
  )
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
